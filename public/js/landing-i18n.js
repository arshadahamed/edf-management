  function captureEnglishDefaults() {
    if (hasCapturedEnglish) return;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key && EN_CACHE[key] === undefined) {
        EN_CACHE[key] = el.textContent;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key && EN_ATTR_CACHE['ph:' + key] === undefined) {
        EN_ATTR_CACHE['ph:' + key] = el.getAttribute('placeholder') || '';
      }
    });
    hasCapturedEnglish = true;
  }

  function formatHijriForLang(lang) {
    const el = document.getElementById('hijri-date-badge');
    if (!el) return;
    const dyn = DYNAMIC_I18N[lang] || DYNAMIC_I18N.en;
    try {
      const hijri = new Intl.DateTimeFormat(dyn.hijriLocale, {
        day: 'numeric',
        month: 'short',
        year: 'numeric'
      }).format(new Date());
      el.textContent = hijri;
    } catch (e) {
      el.textContent = lang === 'ar' ? '١٤٤٨ هـ' : '1448 AH';
    }
  }

  function applyLanguageToDOM(lang) {
    captureEnglishDefaults();
    const isRtl = lang === 'ar';
    const html = document.documentElement;
    html.setAttribute('lang', lang);
    html.setAttribute('dir', isRtl ? 'rtl' : 'ltr');

    document.body.classList.remove('lang-en', 'lang-ar', 'lang-ta', 'lang-si');
    document.body.classList.add('lang-' + lang);

    const dict = TRANSLATIONS[lang] || {};

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      if (lang === 'en') {
        if (EN_CACHE[key] !== undefined) el.textContent = EN_CACHE[key];
      } else if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (!key) return;
      if (lang === 'en') {
        if (EN_ATTR_CACHE['ph:' + key] !== undefined) el.setAttribute('placeholder', EN_ATTR_CACHE['ph:' + key]);
      } else if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Update language switcher button styles across header & mobile drawer
    document.querySelectorAll('.lang-switch-btn').forEach((btn) => {
      const isMatch = btn.dataset.lang === lang;
      btn.setAttribute('aria-pressed', isMatch ? 'true' : 'false');
      btn.classList.toggle('bg-amber-400', isMatch);
      btn.classList.toggle('text-emerald-950', isMatch);
      btn.classList.toggle('shadow-xs', isMatch);
      btn.classList.toggle('text-emerald-200', !isMatch);
      btn.classList.toggle('hover:text-white', !isMatch);
    });

    formatHijriForLang(lang);
  }

  function setLanguage(lang, notify = false) {
    const clean = SUPPORTED_LANGS.includes(lang) ? lang : 'en';
    currentLang = clean;
    try {
      localStorage.setItem(STORAGE_KEY, clean);
    } catch (e) {}

    applyLanguageToDOM(clean);

    window.dispatchEvent(
      new CustomEvent('edf:langchange', {
        detail: {
          lang: clean,
          isRtl: clean === 'ar',
          bundle: DYNAMIC_I18N[clean] || DYNAMIC_I18N.en
        }
      })
    );

    if (notify && typeof window.edfToast === 'function') {
      const bundle = DYNAMIC_I18N[clean] || DYNAMIC_I18N.en;
      window.edfToast(bundle.toastLabel, bundle.toastDesc);
    }
  }

